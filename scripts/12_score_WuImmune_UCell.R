
# ============================================================
# Script 12: UCell Gene Module Scoring
# Dataset: WuImmune
# Modules: 62 WuImmune-compatible immune modules
#
# Outputs:
#   results/WuImmune_UCell_scores.csv
#   results/WuImmune_UCell_scores.rds
#   data/WuImmune_UCell_scored.rds
#   results/benchmark_UCell.csv
# ============================================================

library(Seurat)
library(UCell)

# ------------------------------------------------------------
# 1. Create output folders
# ------------------------------------------------------------

dir.create("results", showWarnings = FALSE)
dir.create("data", showWarnings = FALSE)

# ------------------------------------------------------------
# 2. Load WuImmune dataset and refined modules
# ------------------------------------------------------------

wu <- readRDS("data/WuImmune_reclustered.rds")

modules <- readRDS(
  "data/WuImmune_62_modules_available.rds"
)

DefaultAssay(wu) <- "RNA"

cat("Cells:", ncol(wu), "\n")
cat("Modules:", length(modules), "\n")

# ------------------------------------------------------------
# 3. Check inputs
# ------------------------------------------------------------

stopifnot(
  inherits(wu, "Seurat"),
  ncol(wu) == 50063,
  length(modules) == 62,
  !is.null(names(modules)),
  !anyDuplicated(names(modules)),
  all(lengths(modules) > 0)
)

missing_genes <- setdiff(
  unique(unlist(modules, use.names = FALSE)),
  rownames(wu[["RNA"]])
)

if (length(missing_genes) > 0) {
  stop(
    "Missing genes: ",
    paste(missing_genes, collapse = ", ")
  )
}

cat("Input checks passed.\n")

# ------------------------------------------------------------
# 4. Calculate UCell scores and measure runtime
# ------------------------------------------------------------

cat("\nStarting UCell scoring...\n")

gc()
start_time <- Sys.time()

wu <- UCell::AddModuleScore_UCell(
  obj = wu,
  features = modules,
  assay = "RNA",
  slot = "data",
  name = "_UCell",
  chunk.size = 500,
  ncores = 1
)

elapsed_seconds <- as.numeric(
  difftime(Sys.time(), start_time, units = "secs")
)

cat(
  "Scoring completed in",
  round(elapsed_seconds, 2),
  "seconds.\n"
)

# ------------------------------------------------------------
# 5. Extract UCell score columns
# ------------------------------------------------------------

score_columns <- paste0(names(modules), "_UCell")

if (!all(score_columns %in% colnames(wu@meta.data))) {
  stop(
    "Some UCell score columns were not found. ",
    "Check the column names generated by UCell."
  )
}

scores <- wu@meta.data[, score_columns, drop = FALSE]

colnames(scores) <- paste0(
  "UCell__",
  names(modules)
)

scores <- data.frame(
  cell_id = rownames(scores),
  scores,
  check.names = FALSE,
  row.names = NULL
)

# ------------------------------------------------------------
# 6. Validate scores
# ------------------------------------------------------------

stopifnot(
  nrow(scores) == ncol(wu),
  ncol(scores) == 63,
  identical(scores$cell_id, colnames(wu)),
  !anyNA(scores[, -1, drop = FALSE])
)

cat("Score validation passed.\n")

# ------------------------------------------------------------
# 7. Save scores and scored Seurat object
# ------------------------------------------------------------

write.csv(
  scores,
  "results/WuImmune_UCell_scores.csv",
  row.names = FALSE
)

saveRDS(
  scores,
  "results/WuImmune_UCell_scores.rds"
)

saveRDS(
  wu,
  "data/WuImmune_UCell_scored.rds"
)

# ------------------------------------------------------------
# 8. Save computational benchmark separately
# ------------------------------------------------------------

benchmark <- data.frame(
  method = "UCell",
  cells = ncol(wu),
  modules = length(modules),
  scoring_seconds = round(elapsed_seconds, 2),
  scoring_minutes = round(elapsed_seconds / 60, 2),
  package_version = as.character(packageVersion("UCell")),
  R_version = R.version.string,
  cores = 1,
  chunk_size = 500,
  installation_difficulty = NA_character_,
  installation_seconds = NA_real_,
  peak_ram_gib = NA_real_,
  timestamp = as.character(Sys.time())
)

write.csv(
  benchmark,
  "results/benchmark_UCell.csv",
  row.names = FALSE
)

# ------------------------------------------------------------
# 9. Print summary
# ------------------------------------------------------------

cat("\n========== UCELL SCORING SUMMARY ==========\n")

cat("Cells scored:", nrow(scores), "\n")
cat("Modules scored:", ncol(scores) - 1, "\n")
cat("Missing scores:", sum(is.na(scores[, -1])), "\n")
cat("Scoring time (seconds):", round(elapsed_seconds, 2), "\n")
cat("Scoring time (minutes):", round(elapsed_seconds / 60, 2), "\n")
cat("Package version:", as.character(packageVersion("UCell")), "\n")

cat("\nSaved files:\n")
cat("results/WuImmune_UCell_scores.csv\n")
cat("results/WuImmune_UCell_scores.rds\n")
cat("data/WuImmune_UCell_scored.rds\n")
cat("results/benchmark_UCell.csv\n")

cat("\nScript 12 completed successfully!\n")
